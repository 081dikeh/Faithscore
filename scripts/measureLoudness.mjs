// node scripts/measureLoudness.mjs path/to/FluidR3Mono_GM.sf3
// Renders every catalog instrument playing the same short phrase at the same
// velocity and writes src/audio/loudnessTrims.js — the gain (dB) that brings
// each one to the same short-term loudness, so a tuba doesn't bury a flute.
import fs from 'node:fs'
import { INSTRUMENTS } from '../src/audio/instruments.js'
import { parseSoundBank, renderWindow, SAMPLE_RATE } from '../src/audio/renderCore.js'

const sfPath = process.argv[2]
const sf = fs.readFileSync(sfPath)
const bank = parseSoundBank(sf.buffer.slice(sf.byteOffset, sf.byteOffset + sf.byteLength))

// a comfortable written register for each instrument (default middle C)
const REF = {
  'bass-guitar': 40, 'double-bass': 40, 'contrabassoon': 36, 'bass-clarinet-bb': 46, 'baritone-sax': 48, 'tuba': 41,
  'euphonium': 50, 'baritone-horn': 50, 'bass-trombone': 41, 'tenor-trombone': 50, 'wagner-tuba': 48, 'french-horn': 55,
  'bassoon': 48, 'cello': 48, 'viola-da-gamba': 48, 'timpani': 45, 'bass-voice': 45, 'baritone-voice': 50, 'tenor-voice': 57, 'ttb-choir': 52,
  'piccolo': 84, 'flute': 74, 'glockenspiel': 84, 'crotales': 88, 'celesta': 79, 'xylophone': 76, 'soprano-voice': 69, 'ssa-choir': 69,
  'mezzo-soprano-voice': 66, 'alto-voice': 62, 'violin': 69, 'violin-1': 69, 'violin-2': 67, 'oboe': 69, 'soprano-sax': 67, 'trumpet-bb': 64,
  'cornet': 64, 'flugelhorn': 60, 'mandolin': 67, 'ukulele': 64, 'banjo': 62, 'harmonica': 67, 'melodica': 67, 'tubular-bells': 67,
}
const PHRASE = [0, 2, 4, 7, 4, 2, 0, 4]   // 8 notes, 0.5 s each, then ring-out
const TARGET_DB = -23                      // short-term (400 ms) RMS the loudest instrument window is brought to

function shortTermDb(x) {
  const win = Math.round(SAMPLE_RATE * 0.4)
  let best = 1e-9
  for (let s = 0; s + win <= x.length; s += Math.round(win / 4)) {
    let sum = 0
    for (let i = s; i < s + win; i++) sum += x[i] * x[i]
    best = Math.max(best, Math.sqrt(sum / win))
  }
  return 20 * Math.log10(best)
}

const trims = {}
for (const inst of INSTRUMENTS) {
  const ref = REF[inst.id] ?? 60
  const events = PHRASE.map((o, i) => ({ t: i * 0.5, d: inst.unpitched ? 0.2 : 0.45, midi: ref + o, vel: inst.unpitched ? 100 : 85 }))
  const track = {
    id: inst.id, program: inst.program, unpitched: inst.unpitched, vib: inst.vib,
    drumKey: inst.drum, drumLow: inst.drumLow ?? null, events,
  }
  const w = await renderWindow(bank, [track], 0, 5)
  const db = shortTermDb(w.stems[0].data)
  trims[inst.id] = Math.max(-14, Math.min(14, +(TARGET_DB - db).toFixed(1)))
  process.stdout.write(`${inst.id.padEnd(22)} ${db.toFixed(1).padStart(6)} dB  → trim ${trims[inst.id] >= 0 ? '+' : ''}${trims[inst.id]}\n`)
}
const out = `// src/audio/loudnessTrims.js — GENERATED by scripts/measureLoudness.mjs. Do not edit by hand.
// Gain in dB that brings each instrument to the same short-term loudness
// (measured by rendering the same phrase through the real sound bank).
export const LOUDNESS_TRIMS = ${JSON.stringify(trims, null, 2)}
`
fs.writeFileSync(new URL('../src/audio/loudnessTrims.js', import.meta.url), out)